// Evaluation harness.
// Runs the scanner against labeled fixtures and computes metrics.
// Generates a reproducible evaluation summary and retains
// sample-level results for FP/FN investigation.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { analyzePdf } from '../analysis/index.js';
import { computeMetrics, perIndicatorPerformance, generateSummary } from './metrics.js';
import { EVALUATION_DATASET, EVALUATION_DATASET_VERSION } from './dataset.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const FIXTURES_DIR = join(__dirname, '..', '..', 'tests', 'fixtures');
const RESULTS_DIR = join(__dirname, '..', '..', 'tests', 'results');

export function computeSHA256Node(buffer) {
  return createHash('sha256').update(buffer).digest('hex');
}

export async function runEvaluation(options = {}) {
  const { threshold = 50, outputDir = RESULTS_DIR } = options;
  const results = [];

  for (const sample of EVALUATION_DATASET) {
    const fixturePath = join(FIXTURES_DIR, sample.fileName);
    const record = {
      sampleId: sample.sampleId,
      fileName: sample.fileName,
      label: sample.label,
      knownIndicators: sample.knownIndicators,
      provenance: sample.provenance,
      notes: sample.notes,
      sha256: null,
      riskScore: null,
      riskLevel: null,
      detectedFindings: [],
      scanStatus: null,
      error: null,
      limitations: []
    };

    if (!existsSync(fixturePath)) {
      record.scanStatus = 'failed';
      record.error = `Fixture not found: ${sample.fileName}`;
      results.push(record);
      continue;
    }

    let buffer;
    try {
      buffer = readFileSync(fixturePath);
    } catch (error) {
      record.scanStatus = 'failed';
      record.error = `Read error: ${error.message}`;
      results.push(record);
      continue;
    }

    record.sha256 = computeSHA256Node(buffer);

    try {
      const analysis = await analyzePdf(buffer.buffer.slice(
        buffer.byteOffset,
        buffer.byteOffset + buffer.byteLength
      ));
      record.scanStatus = analysis.status;
      record.riskScore = analysis.riskAssessment?.score ?? null;
      record.riskLevel = analysis.riskAssessment?.level ?? null;
      record.detectedFindings = (analysis.findings || []).map(f => ({
        findingId: f.findingId,
        indicatorCategory: f.indicatorCategory,
        severity: f.severity,
        detectionRule: f.detectionRule,
        confidence: f.confidence,
        detectionMethod: f.detectionMethod
      }));
      record.limitations = analysis.limitations || [];
      record.error = analysis.error;
    } catch (error) {
      record.scanStatus = 'failed';
      record.error = error.message;
    }

    results.push(record);
  }

  const metrics = computeMetrics(results, { threshold });
  const perIndicator = perIndicatorPerformance(results);
  const summary = generateSummary(metrics, perIndicator);
  const labelDistribution = EVALUATION_DATASET.reduce((counts, sample) => {
    counts[sample.label] = (counts[sample.label] || 0) + 1;
    return counts;
  }, {});

  const evaluation = {
    timestamp: new Date().toISOString(),
    threshold,
    datasetSize: EVALUATION_DATASET.length,
    dataset: {
      name: 'CyberTrace synthetic PDF fixture dataset',
      version: EVALUATION_DATASET_VERSION,
      provenance: 'Controlled PDFs generated by tests/generate-fixtures.js; no external or held-out samples.',
      labelDistribution
    },
    metrics,
    perIndicator,
    summary,
    samples: results
  };

  if (outputDir) {
    mkdirSync(outputDir, { recursive: true });
    writeFileSync(join(outputDir, 'evaluation.json'), JSON.stringify(evaluation, null, 2));
    writeFileSync(join(outputDir, 'summary.txt'), summary);
    writeFileSync(join(outputDir, 'results.csv'), toResultsCsv(results));
  }

  return evaluation;
}

function toResultsCsv(results) {
  const header = [
    'sampleId', 'fileName', 'label', 'knownIndicators', 'sha256',
    'riskScore', 'riskLevel', 'scanStatus', 'detectedIndicators',
    'error', 'limitations'
  ];
  const rows = results.map(r => [
    r.sampleId,
    r.fileName,
    r.label,
    `"${r.knownIndicators.join(';')}"`,
    r.sha256 || '',
    r.riskScore ?? '',
    r.riskLevel || '',
    r.scanStatus || '',
    `"${r.detectedFindings.map(f => f.indicatorCategory).join(';')}"`,
    `"${(r.error || '').replace(/"/g, '""')}"`,
    `"${r.limitations.join('; ').replace(/"/g, '""')}"`
  ].join(','));
  return [header, ...rows].join('\n');
}

export async function runAndReport(options = {}) {
  const evaluation = await runEvaluation(options);
  console.log(evaluation.summary);
  return evaluation;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  runAndReport().catch(error => {
    console.error('Evaluation failed:', error);
    process.exit(1);
  });
}